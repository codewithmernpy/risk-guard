"""RiskGuard — Page 5: Trade Journal, Behavioural Red Flags, Discipline & Risk of Ruin."""

from __future__ import annotations

import pandas as pd
import streamlit as st

from riskguard.io import load_journal_csv
from riskguard.ui.charts import (
    chart_equity_and_drawdown,
    chart_r_distribution,
    chart_risk_of_ruin,
)
from riskguard.ui.state import (
    build_session_context,
    init_session_state,
    is_new_upload,
    load_demo_defaults,
    refresh_market_cache,
)
from riskguard.ui.theme import configure_page, render_footer, render_sidebar, status_badge_html

configure_page("Journal & Discipline", icon="🧠")
init_session_state()

st.title("🧠 Trade Journal, Behaviour & Drawdown Schedule")
st.caption("Equity curve, drawdown depth/duration, behavioural leaks (revenge trading, overtrading, escalation, disposition, tilt), discipline score, and risk of ruin.")

with st.expander("Upload Closed-Trade Journal CSV", expanded=False):
    j_file = st.file_uploader(
        "Upload Journal CSV (opened_at, closed_at, symbol, side, quantity, entry_price, exit_price, planned_stop, fees, pnl)",
        type=["csv"],
        key="journal_uploader",
    )
    if is_new_upload("journal", j_file):
        try:
            trades = load_journal_csv(j_file.getvalue())
            st.session_state["journal_trades"] = trades
            st.session_state["journal_is_synthetic"] = any((t.source or "").upper() == "SYNTHETIC" for t in trades)
            st.session_state.pop("_journal_digest", None)
            st.session_state.pop("_ctx_cache_digest", None)
            st.success(f"Loaded {len(trades)} journal trades from {j_file.name}.")
            st.rerun()
        except Exception as exc:
            st.error(f"Failed to parse journal CSV: {exc}")

ctx = build_session_context()
render_sidebar(
    market=ctx.market,
    on_load_demo=load_demo_defaults,
    on_refresh_market=refresh_market_cache,
)

j = ctx.journal
if st.session_state.get("journal_is_synthetic", False):
    st.info(
        f"🧪 **SYNTHETIC DEMO JOURNAL ACTIVE** ({len(st.session_state.get('journal_trades', []))} simulated trades "
        "generated by `python -m riskguard generate-demo`, with planted tilt, revenge-trading, size-escalation "
        "and stop-violation episodes). Today/this-week PnL is evaluated as of its last trading day "
        f"({j.reference_date if j is not None else 'n/a'})."
    )
if j is None or j.total_trades == 0:
    st.warning("No journal trades loaded. Upload a CSV or click Load Demo Data in the sidebar.")
    render_footer()
    st.stop()

# Top metrics
d_lvl = "OK" if j.discipline_score >= 80 else ("WARN" if j.discipline_score >= 65 else "DANGER")
st.markdown(
    f"**Discipline Score:** {status_badge_html(f'{j.discipline_score:.1f} / 100 (Grade {j.discipline_grade})', d_lvl)}",
    unsafe_allow_html=True,
)

c1, c2, c3, c4, c5, c6 = st.columns(6)
c1.metric("Total Trades", str(j.total_trades), f"Win {j.win_rate * 100:.1f}%", delta_color="off", delta_arrow="off")
c2.metric("Total Net PnL", f"{'+' if (j.total_pnl_usd) >= 0 else '-'}${abs(j.total_pnl_usd):,.0f}", f"Fees ${j.total_fees_usd:,.0f}", delta_color="off", delta_arrow="off")
exp_color = "normal" if j.expectancy_usd > 0 else ("red" if j.expectancy_usd < 0 else "off")
exp_arrow = "up" if j.expectancy_usd > 0 else ("down" if j.expectancy_usd < 0 else "off")
c3.metric("Profit Factor", f"{j.profit_factor:.2f}", f"Exp ${j.expectancy_usd:+,.2f}/trade", delta_color=exp_color, delta_arrow=exp_arrow)
c4.metric("Avg R / Payoff", f"{j.avg_r:+.2f}R" if j.avg_r is not None else "N/A", f"Payoff {j.payoff_ratio:.2f}x", delta_color="off", delta_arrow="off")
c5.metric("Max Drawdown", f"{j.max_drawdown_pct:.2f}%", f"Now {j.current_drawdown_pct:.2f}% ({j.max_drawdown_duration_hours:.0f}h)", delta_color="off", delta_arrow="off")
c6.metric("Disposition Ratio", f"{j.disposition_ratio:.2f}x", f"Loss {j.avg_loss_hold_minutes:.0f}m / Win {j.avg_win_hold_minutes:.0f}m", delta_color="off", delta_arrow="off")

st.plotly_chart(chart_equity_and_drawdown(j), width="stretch")

# Discipline score breakdown + Episode counts
b_col1, b_col2 = st.columns([1.0, 1.3])
with b_col1:
    st.subheader("Discipline Score Components (0–100)")
    comp_df = pd.DataFrame(
        [
            {"Component": name, "Score": vals["score"], "Max": vals["max"], "Detail": vals["detail"]}
            for name, vals in j.discipline_components.items()
        ]
    )
    st.dataframe(comp_df, width="stretch", hide_index=True)

with b_col2:
    st.subheader("Flagged Behavioural Episodes Timeline")
    if j.episodes:
        ep_types = sorted({e.episode_type for e in j.episodes})
        selected_types = st.multiselect("Filter Episode Types", options=ep_types, default=ep_types, key="ep_filter")
        filtered = [e for e in j.episodes if e.episode_type in selected_types]
        ep_df = pd.DataFrame(
            [
                {
                    "Time (UTC)": e.timestamp.strftime("%Y-%m-%d %H:%M"),
                    "Type": e.episode_type,
                    "Symbol": e.symbol,
                    "Severity": e.severity,
                    "Description": e.description,
                }
                for e in reversed(filtered[-100:])
            ]
        )
        st.dataframe(ep_df, width="stretch", hide_index=True, height=280)
    else:
        st.success("Zero behavioural red flags detected.")

st.divider()
st.subheader("R-Multiple Distribution & Time / Asset Breakdowns")
r_col, sym_col = st.columns([1.1, 1.1])
with r_col:
    st.plotly_chart(chart_r_distribution(j), width="stretch")
with sym_col:
    tab_sym, tab_wd, tab_hr = st.tabs(["By Symbol", "By Weekday", "By Hour (UTC)"])
    with tab_sym:
        st.dataframe(pd.DataFrame(j.by_symbol).round(2), width="stretch", hide_index=True)
    with tab_wd:
        st.dataframe(pd.DataFrame(j.by_weekday).round(2), width="stretch", hide_index=True)
    with tab_hr:
        st.dataframe(pd.DataFrame(j.by_hour).round(2), width="stretch", hide_index=True)

st.divider()
st.subheader("📉 Drawdown Risk Schedule & Risk of Ruin")
dd_col1, dd_col2 = st.columns([1.1, 1.1])
with dd_col1:
    if ctx.drawdown_plan is not None:
        dp = ctx.drawdown_plan
        st.markdown(
            f"- **Current Drawdown:** `{dp.current_dd_pct:.2f}%` (Limit `{dp.max_dd_limit_pct:.1f}%`)\n"
            f"- **Step-Down Risk:** `{dp.step_down_risk_pct:.2f}%` (`{dp.step_down_multiplier:.2f}x` base `{dp.base_risk_pct:.2f}%`)\n"
            f"- **CPPI Risk:** `{dp.cppi_risk_pct:.2f}%` (Cushion `${dp.cppi_cushion_usd:,.2f}`, `{dp.cppi_multiplier:.2f}x`)\n"
            f"- **Recommended Risk Per Trade:** **`{dp.recommended_risk_pct:.2f}%`**"
        )
        sched_df = pd.DataFrame([t.model_dump() for t in dp.schedule_table])
        st.dataframe(sched_df, width="stretch", hide_index=True)

with dd_col2:
    if ctx.risk_of_ruin is not None:
        ror = ctx.risk_of_ruin
        st.plotly_chart(chart_risk_of_ruin(ror), width="stretch")
        st.caption(
            f"Ruin = equity ever falls {ror.ruin_drawdown_pct:.0f}% below its starting value. Analytical: "
            f"infinite horizon, win rate {ror.win_rate * 100:.1f}%, payoff ratio {ror.payoff_ratio:.2f}, "
            f"risk {ror.risk_per_trade_pct:.2f}%/trade. Monte Carlo: {ror.simulations:,} paths x "
            f"{ror.horizon_trades} trades (flat risk vs the drawdown step-down schedule). "
            f"Flat-risk paths: median terminal equity ${ror.mc_median_terminal_equity:,.0f}, "
            f"5th pct ${ror.mc_p05_terminal_equity:,.0f}, 95th pct worst peak-to-trough drawdown "
            f"{ror.mc_p95_max_dd_pct:.1f}%."
        )

render_footer()
